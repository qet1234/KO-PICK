insert into public.place_categories(code, name)
select distinct lower(regexp_replace(category, '[^[:alnum:]가-힣]+', '_', 'g')), category
from public.tour_places
where active and category is not null and btrim(category) <> ''
on conflict (code) do update set name = excluded.name, updated_at = now();

insert into public.place_regions(region_name, city_name, area_code, sigungu_code)
select distinct coalesce(nullif(btrim(region), ''), '전국'), coalesce(btrim(city), ''), coalesce(btrim(area_code), ''), coalesce(btrim(sigungu_code), '')
from public.tour_places
where active
on conflict (region_name, city_name, area_code, sigungu_code) do update set active = true, updated_at = now();

insert into public.place_sources(place_id, provider, external_id, external_url, last_synced_at)
select id, coalesce(nullif(lower(btrim(source)), ''), 'manual'), coalesce(nullif(btrim(external_id), ''), id::text), source_url, coalesce(last_synced_at, updated_at, now())
from public.places
on conflict (provider, external_id) do update set place_id = excluded.place_id, external_url = excluded.external_url, last_synced_at = excluded.last_synced_at, updated_at = now();

insert into public.place_images(place_id, image_url, source, license_type, is_primary)
select id, thumbnail_url, coalesce(nullif(lower(btrim(source)), ''), 'manual'), image_license, true
from public.places
where thumbnail_url is not null and btrim(thumbnail_url) <> ''
on conflict (place_id, image_url) do update set source = excluded.source, license_type = excluded.license_type, is_primary = true;

create or replace function public.refresh_place_popularity()
returns void
language plpgsql
security invoker
set search_path = public
as $$
begin
  insert into public.place_popularity(provider, external_id, views_1d, views_7d, views_30d, favorites_30d, routes_30d, shares_30d, score, calculated_at)
  select
    e.provider,
    e.external_id,
    count(*) filter (where e.event_type in ('view','detail') and e.created_at >= now() - interval '1 day'),
    count(*) filter (where e.event_type in ('view','detail') and e.created_at >= now() - interval '7 days'),
    count(*) filter (where e.event_type in ('view','detail') and e.created_at >= now() - interval '30 days'),
    count(*) filter (where e.event_type = 'favorite' and e.created_at >= now() - interval '30 days'),
    count(*) filter (where e.event_type = 'route' and e.created_at >= now() - interval '30 days'),
    count(*) filter (where e.event_type = 'share' and e.created_at >= now() - interval '30 days'),
    (count(*) filter (where e.event_type in ('view','detail') and e.created_at >= now() - interval '7 days'))::numeric
      + (count(*) filter (where e.event_type = 'favorite' and e.created_at >= now() - interval '30 days')) * 4
      + (count(*) filter (where e.event_type = 'route' and e.created_at >= now() - interval '30 days')) * 3
      + (count(*) filter (where e.event_type = 'share' and e.created_at >= now() - interval '30 days')) * 5,
    now()
  from public.place_click_events e
  where e.created_at >= now() - interval '30 days'
  group by e.provider, e.external_id
  on conflict (provider, external_id) do update set
    views_1d = excluded.views_1d,
    views_7d = excluded.views_7d,
    views_30d = excluded.views_30d,
    favorites_30d = excluded.favorites_30d,
    routes_30d = excluded.routes_30d,
    shares_30d = excluded.shares_30d,
    score = excluded.score,
    calculated_at = excluded.calculated_at;
end;
$$;

revoke all on function public.refresh_place_popularity() from public, anon, authenticated;
grant execute on function public.refresh_place_popularity() to service_role;
